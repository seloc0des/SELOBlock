// Build-time compiler for the Public Suffix List.
//
//   node scripts/build-psl.js
//
// Fetches the official PSL, normalizes each rule to ASCII (punycode), and writes
// a compact committed artifact at src/quality/psl-data.js. The shipped extension
// reads only that artifact and never touches the network for eTLD+1 resolution.
//
// Re-run this occasionally to refresh. eTLD+1 boundaries are stable, so a
// snapshot is fine between refreshes. Mirrors the build-rulesets.js convention.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { domainToASCII } from 'node:url';
import path from 'node:path';

const PSL_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/quality/psl-data.js'
);

// Convert a rule to ASCII, preserving the leading '!' (exception) and '*.'
// (wildcard) markers, which are not part of the domain to be punycoded.
function toAsciiRule(rule) {
  let prefix = '';
  if (rule.startsWith('!')) {
    prefix = '!';
    rule = rule.slice(1);
  }
  if (rule.startsWith('*.')) {
    prefix += '*.';
    rule = rule.slice(2);
  }
  const ascii = domainToASCII(rule);
  return prefix + (ascii || rule);
}

async function main() {
  console.log(`Fetching PSL from ${PSL_URL} ...`);
  const res = await fetch(PSL_URL, { headers: { 'Cache-Control': 'no-cache' } });
  if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
  const text = await res.text();

  const rules = [];
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('//')) continue;
    rules.push(toAsciiRule(line.toLowerCase()));
  }

  // Deduplicate while preserving order.
  const unique = Array.from(new Set(rules));
  console.log(`Parsed ${unique.length} rules.`);

  const body = unique.join('\n');
  const file = `// GENERATED by scripts/build-psl.js -- do not edit by hand.
// Public Suffix List (https://publicsuffix.org/), ${unique.length} rules.
// Re-run: node scripts/build-psl.js

export const PSL_RULE_COUNT = ${unique.length};

// Rules are newline-joined to keep this file compact; the runtime splits into a
// Set once at module load. '!' prefixes exceptions, '*.' prefixes wildcards.
const RULES = ${JSON.stringify(body)};

export const PSL_RULES = new Set(RULES.split('\\n'));
`;

  await writeFile(OUT, file, 'utf8');
  console.log(`Wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
